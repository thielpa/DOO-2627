import { DomainError } from "../shared/domain-error";
import { Delivery, type DeliveryChannel } from "./delivery";

export type NotificationType = "TURN_PASSED" | "MATCH_COMPLETED" | "MATCH_EXPIRED";

/** Small, flat facts carried by the event; the frontend builds the human text from them. */
export type NotificationData = Record<string, string | number | null>;

export interface NewNotification {
  recipientId: string;
  type: NotificationType;
  eventId: string;
  matchId: string;
  data: NotificationData;
  channels: readonly DeliveryChannel[];
  /** One ID per channel, same order (generated by the caller). */
  deliveryIds: readonly string[];
}

/** Something a Player should know about, created from a domain event of another context. */
export class Notification {
  // Public for MikroORM hydration; application code should use create.
  constructor(
    private readonly _id: string,
    private readonly _recipientId: string,
    private readonly _type: NotificationType,
    private readonly _eventId: string,
    private readonly _matchId: string,
    private readonly _data: NotificationData,
    private readonly _createdAt: Date,
    private _readAt: Date | null,
    private _updatedAt: Date,
    // A plain array when created, a MikroORM collection when hydrated; only iterated here.
    private readonly _deliveries: Iterable<Delivery>,
  ) {}

  static create(id: string, input: NewNotification, createdAt: Date): Notification {
    if (!id) throw new DomainError("CONFLICT", "Notification ID cannot be empty");
    if (!input.recipientId || !input.eventId || !input.matchId) {
      throw new DomainError("CONFLICT", "Notification recipient, event and match are required");
    }
    if (!Number.isFinite(createdAt.getTime())) {
      throw new DomainError("CONFLICT", "Notification creation time must be a valid date");
    }
    if (input.channels.length === 0 || input.channels.length !== input.deliveryIds.length) {
      throw new DomainError("CONFLICT", "Each channel needs exactly one delivery ID");
    }
    if (new Set(input.channels).size !== input.channels.length) {
      throw new DomainError("CONFLICT", "Notification channels must be unique");
    }

    const deliveries: Delivery[] = [];
    const notification = new Notification(
      id,
      input.recipientId,
      input.type,
      input.eventId,
      input.matchId,
      { ...input.data },
      createdAt,
      null,
      createdAt,
      deliveries,
    );
    input.channels.forEach((channel, index) => {
      deliveries.push(new Delivery(input.deliveryIds[index] as string, notification, channel));
    });
    return notification;
  }

  get id(): string {
    return this._id;
  }

  get recipientId(): string {
    return this._recipientId;
  }

  get type(): NotificationType {
    return this._type;
  }

  get eventId(): string {
    return this._eventId;
  }

  get matchId(): string {
    return this._matchId;
  }

  get data(): NotificationData {
    return { ...this._data };
  }

  get createdAt(): Date {
    return this._createdAt;
  }

  get readAt(): Date | null {
    return this._readAt;
  }

  /** Changes when the Notification is read or becomes visible. */
  get updatedAt(): Date {
    return this._updatedAt;
  }

  get deliveries(): readonly Delivery[] {
    return [...this._deliveries];
  }

  /** The delivery for a channel; sender and relay use it to record outcomes. */
  deliveryFor(channel: DeliveryChannel): Delivery | null {
    return this.deliveries.find((delivery) => delivery.channel === channel) ?? null;
  }

  /** Visible in the bell once the IN_APP delivery has been sent by the relay. */
  isVisibleInApp(): boolean {
    return this.deliveryFor("IN_APP")?.status === "SENT";
  }

  /** When the IN_APP delivery was sent, i.e. when the Notification entered the bell stream. */
  visibleAt(): Date | null {
    const delivery = this.deliveryFor("IN_APP");
    return delivery?.status === "SENT" ? delivery.sentAt : null;
  }

  /** Idempotent: the first read time is kept. */
  markRead(at: Date): void {
    if (this._readAt) return;
    if (!Number.isFinite(at.getTime()) || at.getTime() < this._createdAt.getTime()) {
      throw new DomainError("CONFLICT", "Read time must be valid and not precede creation");
    }
    this._readAt = at;
    this._updatedAt = at;
  }

  /** Records a successful send over a channel and refreshes updatedAt. */
  recordDeliverySuccess(deliveryId: string, at: Date): void {
    this.deliveryById(deliveryId).recordSuccess(at);
    this._updatedAt = at;
  }

  recordDeliveryFailure(deliveryId: string, error: string, at: Date, maxAttempts: number): void {
    this.deliveryById(deliveryId).recordFailure(error, at, maxAttempts);
  }

  private deliveryById(deliveryId: string): Delivery {
    const delivery = this.deliveries.find((candidate) => candidate.id === deliveryId);
    if (!delivery) throw new DomainError("NOT_FOUND", "Delivery not found");
    return delivery;
  }
}
